-- Portable between PostgreSQL and H2 (PostgreSQL mode, used by tests).
-- Synthetic data only: payment_method_token is an opaque "tok_*" string, never a card number.

CREATE TABLE payments (
    id                   VARCHAR(36)              PRIMARY KEY,
    idempotency_key      VARCHAR(255)             NOT NULL,
    request_hash         VARCHAR(64)              NOT NULL,
    merchant_id          VARCHAR(64)              NOT NULL,
    amount_minor         BIGINT                   NOT NULL,
    currency             VARCHAR(3)               NOT NULL,
    payment_method_token VARCHAR(64)              NOT NULL,
    status               VARCHAR(16)              NOT NULL,
    failure_code         VARCHAR(64),
    version              BIGINT                   NOT NULL DEFAULT 0,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_payments_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_payments_amount_positive CHECK (amount_minor > 0),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'PROCESSING', 'SUCCEEDED', 'DECLINED', 'FAILED'))
);

CREATE TABLE payment_attempts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id     VARCHAR(36)              NOT NULL,
    attempt_number INT                      NOT NULL,
    outcome        VARCHAR(24)              NOT NULL,
    error_code     VARCHAR(64),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_attempts_payment FOREIGN KEY (payment_id) REFERENCES payments (id),
    CONSTRAINT uk_attempts_payment_number UNIQUE (payment_id, attempt_number)
);
